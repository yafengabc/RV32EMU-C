// benchrun measures pure emulation throughput for the reference Go emulator
// (github.com/yafengabc/RV32EMU).
//
// It is the same batch loop as that project's main.go (RunHot(1000) + TIMG0
// TickN) but excludes ELF loading, process startup and console I/O from the
// timed region, so the number is directly comparable with `rv32emu-c -bench`.
//
// How compare.ps1 uses it (no edits to the Go repository):
//
//  1. `benchrun --stage <GoDir> <OutDir>` copies the emulator packages
//     internal/{cpu,elf,mem,perip,rom} from the checkout into
//     <OutDir>/benchenv/internal/<pkg> (verbatim, so their imports of each
//     other still resolve).
//  2. It then emits this file into <OutDir>/benchenv/internal/benchrun/main.go
//     with the import
//     block replaced by calls into those staged copies.
//  3. compare.ps1 writes a go.mod whose module path is "rv32emu" and runs
//     `go build ./benchenv/internal/benchrun` in <OutDir>. Go's internal-package rule is a path
//     prefix check, so packages under the "rv32emu" module may import the
//     staged emulator code, and the checkout itself is never modified.
//
// The loop body must track the Go emulator's main.go: if its batch loop
// changes, update the measure() function below.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
	// IMPORT_EMULATOR - replaced by the staged package paths below
)

// emulatorPackages are the packages of the Go emulator the harness uses. They
// are staged verbatim; imports between them keep their rv32emu/internal/...
// paths and resolve to each other inside the staged tree.
var emulatorPackages = []string{"cpu", "elf", "mem", "perip", "rom"}

// stagedImportBase replaces the emulator's "rv32emu/internal" prefix.
const stagedImportBase = "rv32emu/benchenv/internal"

// stagedInternalPath is where those packages live on disk: the tail of
// stagedImportBase below the module root (module path "rv32emu").
const stagedInternalPath = "benchenv/internal"

func main() {
	mode := ""
	if len(os.Args) > 1 {
		mode = os.Args[1]
	}
	switch mode {
	case "--emit-main":
		fmt.Print(harnessSource())
	case "--stage":
		if len(os.Args) < 4 {
			fmt.Fprintln(os.Stderr, "usage: benchrun --stage <go-repo> <out-dir>")
			os.Exit(2)
		}
		if err := stage(os.Args[2], os.Args[3]); err != nil {
			fmt.Fprintln(os.Stderr, "stage:", err)
			os.Exit(1)
		}
	default:
		run()
	}
}

// harnessSource renders this file with the emulator imports pointed at the
// staged copies. This is the copy that gets compiled.
func harnessSource() string {
	src, err := os.ReadFile(sourcePath())
	if err != nil {
		fmt.Fprintln(os.Stderr, "benchrun: reading own source:", err)
		os.Exit(1)
	}
	// Staged emulator sources are copied with one rewrite
	// (rv32emu/internal/<pkg> -> *_pkgImport/<pkg>). Go resolves those paths
	// to the staged copies inside the scratch module, and the harness must
	// import exactly the same paths: importing a package under a second path
	// would give it a second package identity, and the staged perip (which
	// imports the staged cpu) would not see the harness's CPU type.
	text := string(src)
	var block strings.Builder
	for _, pkg := range emulatorPackages {
		text = strings.ReplaceAll(text, strconv.Quote("rv32emu/internal/"+pkg),
			strconv.Quote(stagedImportBase+"/"+pkg))
		fmt.Fprintf(&block, "\t%q\n", stagedImportBase+"/"+pkg)
	}
	text = strings.ReplaceAll(text, "\t// IMPORT_EMULATOR - replaced by the staged package paths below\n", block.String())
	startMark := strings.Index(text, "// MEASURE-BODY\n")
	endMark := strings.Index(text, "// MEASURE-BODY-END\n")
	if startMark < 0 || endMark < 0 {
		fmt.Fprintln(os.Stderr, "benchrun: measure body markers missing")
		os.Exit(1)
	}
	start := startMark + len("// MEASURE-BODY\n")
	text = text[:start] + "func measureBody(elfPath string, flash []byte, max uint64) uint64 {\n" +
		measureBodySource + "}\n\n" + text[endMark:]
	return "// Code generated by benchrun --stage. Do not edit.\n" + text
}

// sourcePath locates this file. Depending on how it was built it is either
// copied into <stage>/zh/main.go by compare.ps1 (go run/copy in a scratch
// module) or reached from the vendored copy through benchdata/benchrun.
func sourcePath() string {
	var candidates []string
	if p, err := os.Executable(); err == nil {
		dir := filepath.Dir(p)
		candidates = append(candidates,
			filepath.Join(dir, "zh", "main.go"),
			filepath.Join(dir, "..", "benchdata", "benchrun", "main.go"))
	}
	candidates = append(candidates, filepath.Join("zh", "main.go"), filepath.Join("benchdata", "benchrun", "main.go"))
	for _, c := range candidates {
		if _, err := os.Stat(c); err == nil {
			abs, err := filepath.Abs(c)
			if err == nil {
				return abs
			}
			return c
		}
	}
	return candidates[0]
}

// stage copies the emulator packages and writes the rewritten harness into
// <out>/benchenv/internal/benchrun (the caller supplies go.mod).
func stage(goRepo, outDir string) error {
	// the harness must live under the staged "internal" directory: Go only
	// allows internal imports from packages rooted there
	stagePkg := filepath.Join(outDir, filepath.FromSlash(stagedInternalPath))
	if err := os.MkdirAll(stagePkg, 0o755); err != nil {
		return err
	}
	for _, pkg := range emulatorPackages {
		if err := copyTree(filepath.Join(goRepo, "internal", pkg), filepath.Join(stagePkg, pkg)); err != nil {
			return err
		}
	}
	hc := filepath.Join(stagePkg, "benchrun")
	if err := os.MkdirAll(hc, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(hc, "main.go"), []byte(harnessSource()), 0o644)
}

func copyTree(src, dst string) error {
	entries, err := os.ReadDir(src)
	if err != nil {
		return fmt.Errorf("%w (is the -GoRepo path a checkout of github.com/yafengabc/RV32EMU?)", err)
	}
	if err := os.MkdirAll(dst, 0o755); err != nil {
		return err
	}
	for _, e := range entries {
		from := filepath.Join(src, e.Name())
		to := filepath.Join(dst, e.Name())
		if e.IsDir() {
			if err := copyTree(from, to); err != nil {
				return err
			}
			continue
		}
		if !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		data, err := os.ReadFile(from)
		if err != nil {
			return err
		}
		// the copied packages keep importing rv32emu/internal/<pkg>; point
		// those at the staged copies so the scratch module resolves them
		text := string(data)
		for _, pkg := range emulatorPackages {
			text = strings.ReplaceAll(text, strconv.Quote("rv32emu/internal/"+pkg),
				strconv.Quote(stagedImportBase+"/"+pkg))
		}
		if err := os.WriteFile(to, []byte(text), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func run() {
	elfPath := flag.String("elf", "", "ELF firmware")
	ramdisk := flag.String("ramdisk", "", "littlefs image (optional)")
	max := flag.Uint64("max", 0, "instruction budget per run (0=until halt)")
	reps := flag.Int("reps", 5, "repetitions")
	flag.Parse()
	if *elfPath == "" {
		fmt.Fprintln(os.Stderr, "need -elf")
		os.Exit(2)
	}

	flash := make([]byte, 0x400000)
	if *ramdisk != "" {
		img, err := os.ReadFile(*ramdisk)
		if err != nil {
			fmt.Fprintln(os.Stderr, "ramdisk:", err)
			os.Exit(1)
		}
		copy(flash[0x100000:], img)
	}

	times := make([]float64, 0, *reps)
	var inst uint64
	for i := 0; i < *reps; i++ {
		var dt float64
		inst, dt = measure(*elfPath, flash, *max)
		times = append(times, dt)
		fmt.Printf("[bench] rep=%d sec=%.6f mips=%.2f\n", i+1, dt, float64(inst)/dt/1e6)
	}
	sort.Float64s(times)
	med := times[len(times)/2]
	fmt.Printf("[bench] median sec=%.6f inst=%d mips=%.2f\n", med, inst, float64(inst)/med/1e6)
}

// measureBody is spliced into the emitted harness between the MEASURE-BODY
// markers. It must construct the machine the way the Go emulator's main.go does
// and run the same RunHot(1000) + TIMG0 TickN batch loop.
const measureBodySource = `	bus := mem.NewSystemBus()
	uart := perip.NewUART0()
	gpio := perip.NewGPIO()
	usj := perip.NewUSJ()
	rtc := perip.NewRTC()
	bus.Attach(mem.DeviceRange{Base: perip.UART0Base, Size: perip.UARTSize, Dev: uart})
	bus.Attach(mem.DeviceRange{Base: perip.GPIOBase, Size: perip.GPIOSize, Dev: gpio})
	bus.Attach(mem.DeviceRange{Base: perip.USJBase, Size: perip.USJSize, Dev: usj})
	bus.Attach(mem.DeviceRange{Base: perip.RTCBase, Size: perip.RTCSize, Dev: rtc})
	bus.AddRAM(perip.FlashEmuBase, 0x400000)
	bus.CopyInto(perip.FlashEmuBase, 0, flash)
	bus.LoadROM(0, rom.BuildROM())

	timer := perip.NewC3Timer(nil)
	intc := perip.NewC3Intc()
	spi1 := perip.NewC3SPI1(bus, perip.FlashEmuBase)
	bus.Attach(mem.DeviceRange{Base: perip.TIMG0Base, Size: perip.TIMG0Size, Dev: timer})
	bus.Attach(mem.DeviceRange{Base: perip.INTMTXBase, Size: perip.INTMTXSize, Dev: intc})
	bus.Attach(mem.DeviceRange{Base: perip.SPI1Base, Size: perip.SPI1Size, Dev: spi1})

	c := cpu.New(bus)
	timer.SetCPU(c)
	entry, err := elf.Load(elfPath, bus)
	if err != nil {
		fmt.Fprintln(os.Stderr, "elf:", err)
		os.Exit(1)
	}
	c.SetPC(entry)

	var n uint64
	for !c.Halted() && (max == 0 || n < max) {
		b := uint64(1000)
		if max != 0 && max-n < b {
			b = max - n
		}
		ran := c.RunHot(b)
		if ran == 0 {
			break
		}
		timer.TickN(ran)
		n += ran
		if rtc.ResetPending() {
			break
		}
	}
	return n
`

// measure returns instructions executed and seconds spent for one session. The
// --stage writer replaces the placeholder body between the markers below with
// measureBodySource, so this file also compiles on its own.
func measure(elfPath string, flash []byte, max uint64) (uint64, float64) {
	start := time.Now()
	ran := measureBody(elfPath, flash, max)
	return ran, time.Since(start).Seconds()
}

